// Generate src/policy/ct_logs.rs from the Google (v3) and Apple CT log lists.
//
//   curl -sSo google.json https://www.gstatic.com/ct/log_list/v3/log_list.json
//   curl -sSo apple.json https://valid.apple.com/ct/log_list/current_log_list.json
//   bun scripts/ct-logs.ts google.json apple.json
//
// Only ECDSA P-256 logs are kept. A log with any other key cannot be verified
// by this provider, so its SCTs never count.

import { createHash } from 'node:crypto';

const [googlePath, applePath] = process.argv.slice(2);
if (!googlePath || !applePath) throw new Error('usage: bun scripts/ct-logs.ts google.json apple.json');
const google = JSON.parse(await Bun.file(googlePath).text());
const apple = JSON.parse(await Bun.file(applePath).text());

// SubjectPublicKeyInfo prefix for id-ecPublicKey with prime256v1, then the
// uncompressed point.
const P256 = Buffer.from('3059301306072a8648ce3d020106082a8648ce3d030107034200', 'hex');

function status(state) {
  if (!state) return 'Status::Never';
  if (state.usable || state.qualified || state.readonly) return 'Status::Always';
  if (state.retired) return 'Status::Before(' + Date.parse(state.retired.timestamp) + ')';
  return 'Status::Never';
}

const logs = new Map();
let dropped = 0;
function collect(list, side) {
  for (const operator of list.operators) {
    for (const log of [...(operator.logs ?? []), ...(operator.tiled_logs ?? [])]) {
      const key = Buffer.from(log.key, 'base64');
      const id = createHash('sha256').update(key).digest();
      if (id.toString('base64') !== log.log_id) throw new Error('log id mismatch: ' + log.description);
      if (key.length !== P256.length + 65 || !key.subarray(0, P256.length).equals(P256)) {
        dropped++;
        continue;
      }
      const hex = id.toString('hex');
      const entry = logs.get(hex) ?? { id, point: key.subarray(P256.length), description: log.description, google: ['Status::Never', ''], apple: ['Status::Never', ''] };
      entry[side] = [status(log.state), operator.name];
      logs.set(hex, entry);
    }
  }
}
collect(google, 'google');
collect(apple, 'apple');

const bytes = (b) => '[' + [...b].map((x) => '0x' + x.toString(16).padStart(2, '0')).join(', ') + ']';
const live = [...logs.values()].filter((l) => l.google[0] !== 'Status::Never' || l.apple[0] !== 'Status::Never');
live.sort((a, b) => Buffer.compare(a.id, b.id));

let out = '';
out += '//! Generated by scripts/ct-logs.ts; do not edit by hand.\n';
out += '//!\n';
out += '//! Google log list v3 version ' + google.version + ' (' + google.log_list_timestamp + '), Apple log list version ' + apple.version + '.\n';
out += '//! ' + live.length + ' ECDSA P-256 logs; ' + dropped + ' list entries with other keys left out.\n\n';
out += 'use super::{Log, Status};\n\n';
out += '/// Sorted by log id.\n';
out += 'pub(super) static LOGS: &[Log] = &[\n';
for (const l of live) {
  out += '    // ' + l.description + '\n';
  out += '    Log {\n';
  out += '        id: ' + bytes(l.id) + ',\n';
  out += '        key: ' + bytes(l.point) + ',\n';
  out += '        google: ' + l.google[0] + ',\n';
  out += '        google_operator: ' + JSON.stringify(l.google[1]) + ',\n';
  out += '        apple: ' + l.apple[0] + ',\n';
  out += '        apple_operator: ' + JSON.stringify(l.apple[1]) + ',\n';
  out += '    },\n';
}
out += '];\n';
await Bun.write('src/policy/ct_logs.rs', out);
console.log('wrote ' + live.length + ' logs, dropped ' + dropped);
